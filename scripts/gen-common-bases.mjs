// Generates js/common-bases.js (sweep W3, controller ruling R19 / SEC #3).
// NOT a test and not run by `npm test`. Usage, from the repo root:
//
//   node scripts/gen-common-bases.mjs <path-to-xato-net-10-million-passwords-1000000.txt>
//
// The input is the SAME pinned SecLists list js/common-passwords.js records
// in its header. It is read as text only, never executed. Each entry is
// reduced with js/password-policy.js's own baseWord() — the function
// checkPassword applies at run time, so the two cannot disagree — bases of
// fewer than 4 letters are dropped, and the most frequent 5,000 are kept
// (ties: first appearance in the list). 'plaenicke' and 'lmu' are added.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { baseWord, MIN_BASE_LETTERS } from '../js/password-policy.js';

const SOURCE_URL = 'https://raw.githubusercontent.com/danielmiessler/SecLists/b68489393c7a9bc20f15947b63509a9cbeeb3f92/Passwords/Common-Credentials/xato-net-10-million-passwords-1000000.txt';
const COMMIT = 'b68489393c7a9bc20f15947b63509a9cbeeb3f92';
const LIMIT = 5000;
const SUPPLEMENTARY = ['plaenicke', 'lmu'];

const path = process.argv[2];
if (!path) throw new Error('usage: node scripts/gen-common-bases.mjs <list.txt>');
const raw = readFileSync(path);
const sha256 = createHash('sha256').update(raw).digest('hex');
const entries = raw.toString('utf8').split(/\r?\n/).filter((l) => l.length > 0);

const counts = new Map(); // insertion order = first appearance
for (const e of entries) {
  const b = baseWord(e);
  if ([...b].length < MIN_BASE_LETTERS) continue;
  counts.set(b, (counts.get(b) || 0) + 1);
}
const order = [...counts.keys()];
const rank = new Map(order.map((b, i) => [b, i]));
const top = order.sort((a, b) => (counts.get(b) - counts.get(a)) || (rank.get(a) - rank.get(b))).slice(0, LIMIT);
const minCount = counts.get(top[top.length - 1]);
const extra = SUPPLEMENTARY.filter((w) => !top.includes(w));

const body = `${top.map((w) => JSON.stringify(w)).join(',\n')}`;
const out = `// Common-password BASE WORDS for js/password-policy.js (sweep W3, ruling R19).
// Source: ${SOURCE_URL}
// SecLists commit: ${COMMIT}
// Source file SHA-256: ${sha256} (${entries.length} non-empty entries)
// License: SecLists is MIT-licensed (c) Daniel Miessler and contributors.
// Method: every entry reduced by password-policy.js baseWord() — NFKC,
// lowercase, the leading and trailing runs of non-letters removed, then
// inside what is left 0->o 1->i 3->e 4->a 5->s @->a $->s and every remaining
// non-letter removed. Bases of fewer than ${MIN_BASE_LETTERS} letters dropped. The ${LIMIT} most
// frequent kept (ties: first appearance; the last kept base occurs ${minCount} times).
// Supplementary: ${SUPPLEMENTARY.join(', ')} (${extra.length} added; the rest were already in).
// Total: ${top.length + extra.length} bases.
// Generated by scripts/gen-common-bases.mjs; do not edit by hand.
const FROM_SECLISTS = [
${body}
];

const SUPPLEMENTARY = ${JSON.stringify(extra)};

export const COMMON_BASES = new Set([...FROM_SECLISTS, ...SUPPLEMENTARY]);
`;
writeFileSync(new URL('../js/common-bases.js', import.meta.url), out);
console.log(`bases: ${top.length + extra.length}; min count ${minCount}; bytes ${Buffer.byteLength(out)}; sha256 ${sha256}`);
